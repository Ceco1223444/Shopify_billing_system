// Regenerates packages/core/src/couriers/econt-openapi.ts from Econt's published OpenAPI spec
// (P4-06). Needs internet. Run when Econt changes its API: pnpm econt:types
//
// Note: the live API answers some fields differently from the spec (see docs/STATUS.md,
// "API / tool differences found"); packages/core/src/couriers/econt.ts handles those.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const SPEC_URL = 'https://ee.econt.com/services/openapi.yaml';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'packages/core/src/couriers/econt-openapi.ts');

const ast = await openapiTS(new URL(SPEC_URL));
writeFileSync(
  target,
  `// Generated by \`pnpm econt:types\` from ${SPEC_URL}. Do not edit by hand.\n` +
    `// Generated on ${new Date().toISOString().slice(0, 10)}.\n` +
    astToString(ast).replace(/\r\n/g, '\n'),
);
console.log('Wrote', target);
