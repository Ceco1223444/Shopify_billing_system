// Writes the env files that point the web app and the tests at the LOCAL Supabase stack.
//   apps/web/.env.local     URL + publishable key (reaches the browser)
//   tests/.env.test.local   URL + publishable key + secret key + DB URL (tests only)
// Both files are git-ignored. Usage: pnpm env:local
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { localSupabaseStatus } from './lib/supabase-status.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const s = localSupabaseStatus();

if (!s.publishableKey || !s.secretKey) {
  throw new Error('supabase status did not report the publishable / secret keys');
}

const header = '# Generated by `pnpm env:local` for the LOCAL Supabase stack. Do not commit.\n';

writeFileSync(
  join(root, 'apps/web/.env.local'),
  header +
    `VITE_SUPABASE_URL=${s.apiUrl}\n` +
    `VITE_SUPABASE_PUBLISHABLE_KEY=${s.publishableKey}\n`,
);

writeFileSync(
  join(root, 'tests/.env.test.local'),
  header +
    `SUPABASE_URL=${s.apiUrl}\n` +
    `SUPABASE_PUBLISHABLE_KEY=${s.publishableKey}\n` +
    `SUPABASE_SECRET_KEY=${s.secretKey}\n` +
    `SUPABASE_DB_URL=${s.dbUrl}\n`,
);

console.log('Wrote apps/web/.env.local and tests/.env.test.local for', s.apiUrl);
